import { storeProfileDocument } from '../actions/profileDocuments.js';
import { createHasuraClient } from '../hasura/client.js';
import type { OrgKey, SeedCompaniesResult } from './companies.js';
import { buildPeople, type PersonRole, type PersonSpec } from './peoplePlan.js';
import { renderPdf } from './pdf.js';
import type { SeedContext, SeedTenancyResult } from './tenancy.js';

export type SeedPeopleResult = {
  /** Every seeded profile id, both organizations. */
  all: string[];
  /** Nova Tower profile ids by seed role, in plan order (the faces step assigns faces in this order). */
  byRole: Record<PersonRole, string[]>;
};

const EXISTING = `
  query SeedProfilesExisting($org: uuid!) {
    profiles(where: { organization_id: { _eq: $org }, external_id: { _like: "seed:%" } }) {
      id external_id profile_documents { title }
    }
  }
`;
const INSERT = `
  mutation SeedProfilesInsert($objects: [profiles_insert_input!]!) {
    insert_profiles(objects: $objects) { affected_rows }
  }
`;

type Existing = { id: string; external_id: string; profile_documents: { title: string }[] };

async function existing(ctx: SeedContext, org: string): Promise<Map<string, Existing>> {
  const { profiles } = await ctx.admin.request<{ profiles: Existing[] }>(EXISTING, { org });
  return new Map(profiles.map((p) => [p.external_id, p]));
}

function insertObject(org: string, key: OrgKey, person: PersonSpec, companies: SeedCompaniesResult): Record<string, unknown> {
  const lookup = (map: Record<string, string>, name: string | null): string | null => {
    if (!name) return null;
    const id = map[`${key}/${name}`];
    if (!id) throw new Error(`seed: unknown company or schedule ${name}`);
    return id;
  };
  return {
    ...person.profile,
    organization_id: org,
    external_id: person.externalId,
    company_id: lookup(companies.companies, person.company),
    work_schedule_id: lookup(companies.schedules, person.schedule),
    // Nested insert: Hasura fills organization_id and profile_id from the parent through the composite FK.
    consent_records: { data: person.consents },
  };
}

/**
 * Inserts the planned people that are missing (keyed by external_id `seed:NNN`) with their consent records, then
 * stores the planned documents that are missing (keyed by title) through the upload_profile_document logic.
 */
export async function seedPeople(
  ctx: SeedContext,
  tenancy: SeedTenancyResult,
  companies: SeedCompaniesResult,
): Promise<SeedPeopleResult> {
  const result: SeedPeopleResult = { all: [], byRole: { employee: [], contractor: [], visitor: [], vip: [], blacklisted: [] } };
  for (const key of Object.keys(tenancy.orgs) as OrgKey[]) {
    const org = tenancy.orgs[key];
    const people = buildPeople(key, ctx.now);
    const before = await existing(ctx, org);
    const missing = people.filter((p) => !before.has(p.externalId));
    if (missing.length > 0) {
      await ctx.admin.request(INSERT, { objects: missing.map((p) => insertObject(org, key, p, companies)) });
    }
    const rows = await existing(ctx, org);
    const actor = createHasuraClient(ctx.env, { role: 'admin', userId: tenancy.users.admin, organizationId: org });
    for (const person of people) {
      const row = rows.get(person.externalId);
      if (!row) throw new Error(`seed: profile ${person.externalId} missing after insert`);
      result.all.push(row.id);
      if (key === 'nova') result.byRole[person.role].push(row.id);
      const doc = person.document;
      if (!doc || row.profile_documents.some((d) => d.title === doc.title)) continue;
      const name = `${person.profile.first_name} ${person.profile.last_name}`;
      await storeProfileDocument(
        { storage: ctx.storage, actor },
        {
          organizationId: org,
          profileId: row.id,
          kind: doc.kind,
          title: doc.title,
          fileName: `${doc.kind}-${person.profile.last_name.toLowerCase()}.pdf`,
          mimeType: 'application/pdf',
          data: renderPdf([doc.title, name, person.company ?? 'Visitor', 'Demo document generated by the ITAP seed.']),
        },
      );
    }
  }
  return result;
}
