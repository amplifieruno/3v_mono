import {
  type DataProvider,
  type MutationContext,
  type QueryContext,
  createMutationDescriptor,
  createQueryDescriptor,
} from '@burojs/core';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createItapHasuraProvider } from '../../src/data/provider';
import { REPORT_FACILITY_RESOURCE, REPORT_RESOURCE, REPORT_SCHEDULE_RESOURCE } from '../../src/data/resource-names';
import { cronSummary } from '../../src/fields/cron-format';
import { presignStorageFile } from '../../src/fields/storage-client';
import { REPORTS_BINDING } from '../../src/modules/analytics/report-ops';
import { reportPeriodProblem } from '../../src/modules/analytics/report-shape';
import { NOVA_FACILITY } from '../support/dev-hosts';
import { ADMIN_EMAIL, DEV_GRAPHQL, DEV_STACK_ENABLED, DEV_STORAGE, NOVA_NAME, devAdminSecret, signInDev } from '../support/dev-stack';

/**
 * Reports of Nova through the console's provider, as `org_admin`: a small report requested with its
 * facility (nested in one insert) is generated by the platform within a bounded wait and its file
 * opens through a presigned link; Retry is refused on a report that has not failed; the server
 * refuses the period the form refuses; a schedule is saved with its cron, refused on an incident
 * template, and deleted; seeded report deliveries reach their report. The report is removed
 * afterwards with the admin secret (with its `report_generated` event, what it fanned out, and its file).
 */

const IDENTITY = { providerId: 'hasura', sessionKey: 'reports-dev-test', scopeKey: null, bindingRevision: '1' } as const;
const session = { sessionKey: IDENTITY.sessionKey, scopeKey: null, generation: 1 };
const mutationContext = (): MutationContext => ({
  signal: new AbortController().signal,
  requestContext: {},
  session,
  providerServiceKey: 'hasura',
  idempotencyKey: crypto.randomUUID(),
});
const queryContext = (): QueryContext => ({ signal: new AbortController().signal, requestContext: {}, session, providerServiceKey: 'hasura' }) as QueryContext;

type Row = Record<string, unknown>;

/** The longest wait for the platform to generate the test report. */
const GENERATION_TIMEOUT_MS = 60_000;

describe.skipIf(!DEV_STACK_ENABLED)('reports against the dev stack (Nova Tower)', () => {
  let provider: DataProvider;
  let token: () => Promise<string | null>;
  let facility = '';
  const reports: string[] = [];
  const schedules: string[] = [];

  const resourceMutation = (resource: string, input: Row) =>
    provider.mutations?.[input.kind as 'createOne']?.(
      createMutationDescriptor({ ...IDENTITY, ref: { namespace: 'default', id: resource }, resource, idField: 'id', ...input } as never) as never,
      mutationContext(),
    );
  const list = async (resource: string, filter: Row): Promise<Row[]> => {
    const { data } = (await provider.queries?.list?.(
      createQueryDescriptor({
        ...IDENTITY,
        kind: 'list',
        ref: { namespace: 'default', id: resource },
        resource,
        pagination: { kind: 'offset', page: 1, pageSize: 50 },
        filter,
      } as never) as never,
      queryContext(),
    )) as { data: Row[] };
    return data;
  };
  const custom = async (kind: 'mutations' | 'queries', operation: string, input: Row): Promise<unknown> => {
    const descriptor = { ...IDENTITY, kind: 'custom', ref: { namespace: 'default', id: operation }, resource: REPORTS_BINDING, operation, input };
    return kind === 'mutations'
      ? provider.mutations?.custom?.(createMutationDescriptor(descriptor as never) as never, mutationContext())
      : provider.queries?.custom?.(createQueryDescriptor(descriptor as never) as never, queryContext());
  };
  const graphql = async (query: string, variables: Row = {}): Promise<Row> => {
    const response = await fetch(DEV_GRAPHQL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${await token()}` },
      body: JSON.stringify({ query, variables }),
    });
    const body = (await response.json()) as { data?: Row; errors?: unknown[] };
    expect(body.errors, JSON.stringify(body.errors)).toBeUndefined();
    return body.data ?? {};
  };
  const newReport = (overrides: Row = {}): Row => ({
    reportType: 'occupancy',
    title: `dev-test report ${Date.now()}`,
    description: null,
    format: 'csv',
    startDate: '2026-10-01',
    endDate: '2026-10-02',
    incidentId: null,
    timezone: 'UTC',
    facilityIds: [facility],
    segmentIds: [],
    ...overrides,
  });

  beforeAll(async () => {
    const auth = await signInDev(ADMIN_EMAIL, NOVA_NAME);
    token = () => auth.getToken();
    provider = createItapHasuraProvider(token, DEV_GRAPHQL);
    const data = await graphql(`{ facilities(where: { name: { _eq: "${NOVA_FACILITY}" } }) { id } }`);
    facility = (data.facilities as { id: string }[])[0]?.id ?? '';
    expect(facility).not.toBe('');
  });

  afterAll(async () => {
    for (const id of schedules) await resourceMutation(REPORT_SCHEDULE_RESOURCE, { kind: 'deleteOne', id });
    const secret = { 'x-hasura-admin-secret': devAdminSecret() };
    for (const id of reports) {
      const rows = await fetch(DEV_GRAPHQL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', ...secret },
        body: JSON.stringify({ query: `{ reports_by_pk(id: "${id}") { file_id } }` }),
      });
      const fileId = ((await rows.json()) as { data?: { reports_by_pk?: { file_id: string | null } } }).data?.reports_by_pk?.file_id;
      // Reports and events are history for every role; the retention context is the one way to remove them.
      // What the report's `report_generated` event fanned out (deliveries, inbox rows, webhook deliveries) goes first.
      const event = `(select e.id from itap.events e where e.dedup_key = 'report:${id}:report_generated')`;
      const sql = [
        "select set_config('itap.retention_context', 'on', true)",
        `delete from itap.notification_deliveries where report_id = '${id}' or event_id in ${event}`,
        `delete from itap.user_notifications where event_id in ${event}`,
        `delete from itap.webhook_deliveries where event_id in ${event}`,
        `delete from itap.events where dedup_key = 'report:${id}:report_generated'`,
        `delete from itap.reports where id = '${id}'`,
      ].join('; ');
      const removed = await fetch(DEV_GRAPHQL.replace('/v1/graphql', '/v2/query'), {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', ...secret },
        body: JSON.stringify({ type: 'run_sql', args: { source: 'default', sql } }),
      });
      expect(removed.ok).toBe(true);
      if (fileId) await fetch(`${DEV_STORAGE}/v1/files/${fileId}`, { method: 'DELETE', headers: secret });
    }
  });

  it('should generate a report requested with its facility and open its file', async () => {
    const created = (await custom('mutations', 'createReport', newReport())) as { id: string; code: string };
    expect(created.code).toMatch(/^REPORT-\d{5}$/u);
    reports.push(created.id);
    // The facility went in with the report, in the same insert.
    expect((await list(REPORT_FACILITY_RESOURCE, { field: 'report_id', op: 'eq', value: created.id })).map((row) => row.facility_id)).toEqual([facility]);

    let progress: Row | null = null;
    const deadline = Date.now() + GENERATION_TIMEOUT_MS;
    while (Date.now() < deadline) {
      progress = (await custom('queries', 'reportProgress', { reportId: created.id })) as Row | null;
      if (progress?.status === 'completed' || progress?.status === 'failed') break;
      await new Promise((resolve) => setTimeout(resolve, 1000));
    }
    expect(progress?.status, JSON.stringify(progress)).toBe('completed');

    const [report] = await list(REPORT_RESOURCE, { field: 'id', op: 'eq', value: created.id });
    expect(report).toMatchObject({
      status: 'completed',
      report_type: 'occupancy',
      format: 'csv',
      parameters: { timezone: 'UTC' },
      requested_by_me: true,
    });
    const { url } = await presignStorageFile(String(report?.file_id), { base: DEV_STORAGE, getToken: token });
    const file = await fetch(url);
    expect(file.status).toBe(200);
    expect((await file.text()).length).toBeGreaterThan(0);

    // Retry is for failed reports only: the database refuses it on a completed one, definitely.
    await expect(custom('mutations', 'retryReport', { reportId: created.id })).rejects.toMatchObject({
      kind: 'validation',
      code: 'report_not_failed',
    });
  }, GENERATION_TIMEOUT_MS + 15_000);

  it('should be refused by the server where the form refuses the period', async () => {
    expect(reportPeriodProblem('2025-01-01', '2026-01-03')?.code).toBe('reportPeriod.tooLong');
    await expect(custom('mutations', 'createReport', newReport({ startDate: '2025-01-01', endDate: '2026-01-03' }))).rejects.toMatchObject({
      kind: 'validation',
      code: 'reports_period',
    });
    // The longest period the form accepts is accepted by the server too (checked without generating: end before start is the other bound).
    expect(reportPeriodProblem('2025-01-01', '2026-01-02')).toBeNull();
    await expect(custom('mutations', 'createReport', newReport({ startDate: '2026-10-02', endDate: '2026-10-01' }))).rejects.toMatchObject({
      code: 'reports_period',
    });
  });

  it('should save a schedule with its cron, refuse an incident template, and delete it', async () => {
    const data = await graphql(
      '{ report_templates(where: { is_system: { _eq: true } }) { id name report_type } recipient_groups(where: { name: { _eq: "Facility managers" } }) { id } }',
    );
    const templates = data.report_templates as { id: string; report_type: string }[];
    const weekly = templates.find((t) => t.report_type === 'occupancy');
    const incident = templates.find((t) => t.report_type === 'incident');
    const group = (data.recipient_groups as { id: string }[])[0]?.id;
    expect(weekly && incident && group).toBeTruthy();

    const cron = '30 6 * * 1-5';
    const result = (await resourceMutation(REPORT_SCHEDULE_RESOURCE, {
      kind: 'createOne',
      input: {
        name: `dev-test schedule ${Date.now()}`,
        template_id: weekly?.id,
        cron,
        timezone: 'Europe/Moscow',
        channel: 'email',
        recipient_group_id: group,
        is_active: false,
      },
    })) as { record: Row };
    schedules.push(String(result.record.id));
    const [saved] = await list(REPORT_SCHEDULE_RESOURCE, { field: 'id', op: 'eq', value: result.record.id });
    expect(saved).toMatchObject({ cron, timezone: 'Europe/Moscow', is_active: false, next_run_at: null });
    expect(cronSummary(saved?.cron)).toBe('At 06:30 on Monday–Friday');

    await expect(
      resourceMutation(REPORT_SCHEDULE_RESOURCE, {
        kind: 'createOne',
        input: { name: `dev-test refused ${Date.now()}`, template_id: incident?.id, cron, timezone: 'UTC', channel: 'webhook', is_active: false },
      }),
    ).rejects.toMatchObject({ message: expect.stringContaining('report_schedule_incident_template') });
    // The server's cron check and the field's agree.
    expect(cronSummary('0 7 * * MON')).toBeNull();
    await expect(
      resourceMutation(REPORT_SCHEDULE_RESOURCE, {
        kind: 'createOne',
        input: { name: `dev-test cron ${Date.now()}`, template_id: weekly?.id, cron: '0 7 * * MON', timezone: 'UTC', channel: 'webhook', is_active: false },
      }),
    ).rejects.toMatchObject({ message: expect.stringContaining('report_schedules_cron_valid') });

    await resourceMutation(REPORT_SCHEDULE_RESOURCE, { kind: 'deleteOne', id: String(result.record.id) });
    schedules.pop();
    expect(await list(REPORT_SCHEDULE_RESOURCE, { field: 'id', op: 'eq', value: result.record.id })).toEqual([]);
  });

  it('should take a report delivery to its report', async () => {
    const data = await graphql('{ notification_deliveries(where: { report_id: { _is_null: false } }, limit: 1) { report_id report { id code } } }');
    const [delivery] = data.notification_deliveries as { report_id: string; report: { id: string; code: string } | null }[];
    expect(delivery, 'a seeded report delivery').toBeDefined();
    expect(delivery?.report?.id).toBe(delivery?.report_id);
  });
});
